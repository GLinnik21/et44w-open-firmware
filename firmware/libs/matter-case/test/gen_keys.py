#!/usr/bin/env python3
"""Extract the operational private keys of connectedhomeip's CHIPCert test certificates into keys.h.
Usage: gen_keys.py <CHIPCert_test_vectors.cpp> > keys.h
Source: https://github.com/project-chip/connectedhomeip/blob/master/src/credentials/tests/CHIPCert_test_vectors.cpp
The certificates themselves come from matter-cert/test/vectors.h (same file, gen_vectors.py)."""
import re, sys

WANT = ('Node01_01', 'Node01_02', 'Node02_01', 'Node02_04', 'Node02_08')
src = open(sys.argv[1]).read()
print('/* Generated by gen_keys.py from connectedhomeip CHIPCert_test_vectors.cpp (Apache-2.0). Do not edit.')
print(' * Private keys (sTestCert_<name>_PrivateKey) of the test certificates in matter-cert/test/vectors.h. */')
print('#ifndef MT_CASE_KEYS_H\n#define MT_CASE_KEYS_H\n#include <stdint.h>\n')
for name in WANT:
    m = re.search(r'sTestCert_%s_PrivateKey\(\(const uint8_t\[\]\)\{(.*?)\}\);' % name, src, re.S)
    b = bytes(int(x, 16) for x in re.findall(r'0x([0-9a-fA-F]{2})', m.group(1)))
    assert len(b) == 32, name
    line = src.count('\n', 0, m.start()) + 1
    rows = [', '.join('0x%02x' % x for x in b[i:i + 16]) for i in range(0, 32, 16)]
    print('/* CHIPCert_test_vectors.cpp line %d */' % line)
    print('static const uint8_t k_%s_priv[32] = {\n    %s\n};' % (name, ',\n    '.join(rows)))
print('\n#endif')
