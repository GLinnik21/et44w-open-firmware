#!/usr/bin/env python3
"""Known answers for the CASE key schedule (Matter spec 4.14.2.3 / 4.14.2.4 / 4.14.2.6), independent of the C code.

Input: the output of `make -C libs/matter-case/test dump` (initiator ephemeral private key, IPK and the raw
Sigma1/Sigma2/Sigma3 payloads of a deterministic run). Recomputes, with the standard library only (its own
P-256 arithmetic, HMAC/HKDF from hmac+hashlib, its own minimal TLV reader):
  shared = ECDH(initiator eph priv, responder eph pub from Sigma2)
  S2K  = HKDF(salt = IPK || responderRandom || responderEphPubKey || SHA256(Sigma1), shared, "Sigma2")
  S3K  = HKDF(salt = IPK || SHA256(Sigma1 || Sigma2), shared, "Sigma3")
  keys = HKDF(salt = IPK || SHA256(Sigma1 || Sigma2 || Sigma3), shared, "SessionKeys", 48)
and prints kat_vectors.h.   Usage (write to a temp file first: make rebuilds while redirecting):
  make -s build/case_test && build/case_test --dump > /tmp/d && python3 -I kat.py < /tmp/d > /tmp/k && mv /tmp/k kat_vectors.h
"""
import hashlib
import hmac
import sys

# NIST P-256 (FIPS 186-4 D.1.2.3)
P = 0xFFFFFFFF00000001000000000000000000000000FFFFFFFFFFFFFFFFFFFFFFFF
A = P - 3
B = 0x5AC635D8AA3A93E7B3EBBD55769886BC651D06B0CC53B0F63BCE3C3E27D2604B


def add(p1, p2):
    if p1 is None:
        return p2
    if p2 is None:
        return p1
    (x1, y1), (x2, y2) = p1, p2
    if x1 == x2 and (y1 + y2) % P == 0:
        return None
    if p1 == p2:
        lam = (3 * x1 * x1 + A) * pow(2 * y1, -1, P) % P
    else:
        lam = (y2 - y1) * pow(x2 - x1, -1, P) % P
    x3 = (lam * lam - x1 - x2) % P
    return x3, (lam * (x1 - x3) - y1) % P


def mul(k, pt):
    r = None
    while k:
        if k & 1:
            r = add(r, pt)
        pt = add(pt, pt)
        k >>= 1
    return r


def point(b):
    assert len(b) == 65 and b[0] == 4
    x, y = int.from_bytes(b[1:33], "big"), int.from_bytes(b[33:], "big")
    assert (y * y - x * x * x - A * x - B) % P == 0, "not on the curve"
    return x, y


def hkdf(salt, ikm, info, n):
    prk = hmac.new(salt, ikm, hashlib.sha256).digest()
    out, t, i = b"", b"", 1
    while len(out) < n:
        t = hmac.new(prk, t + info + bytes([i]), hashlib.sha256).digest()
        out += t
        i += 1
    return out[:n]


def tlv_fields(buf):
    """Top-level context-tagged fields of an anonymous structure: {tag: bytes|int}. Nested structures skipped."""
    assert buf[0] == 0x15
    i, out, depth = 1, {}, 0
    while True:
        ctl = buf[i]
        i += 1
        if ctl == 0x18:
            if depth == 0:
                return out
            depth -= 1
            continue
        tagc, typ = ctl >> 5, ctl & 0x1F
        tag = None
        if tagc == 1:
            tag = buf[i]
            i += 1
        else:
            assert tagc == 0, "only anonymous/context tags expected"
        if typ in (0x15, 0x16, 0x17):
            depth += 1
            continue
        if 0x04 <= typ <= 0x07:  # unsigned int
            n = 1 << (typ - 4)
            v = int.from_bytes(buf[i:i + n], "little")
            i += n
        elif typ in (0x10, 0x11):  # byte string, 1/2-byte length
            n = 1 << (typ - 0x10)
            ln = int.from_bytes(buf[i:i + n], "little")
            i += n
            v = buf[i:i + ln]
            i += ln
        else:
            raise ValueError("unexpected TLV type %#x" % typ)
        if depth == 0:
            out[tag] = v


def c_array(name, b):
    body = ", ".join("0x%02x" % x for x in b)
    return "static const uint8_t %s[%d] = { %s };" % (name, len(b), body)


def main():
    d = {}
    for line in sys.stdin:
        parts = line.split()
        if len(parts) == 2:
            d[parts[0]] = bytes.fromhex(parts[1])
    s1, s2, s3, ipk = d["sigma1"], d["sigma2"], d["sigma3"], d["ipk"]
    f1, f2 = tlv_fields(s1), tlv_fields(s2)
    priv = int.from_bytes(d["ini_eph_priv"], "big")
    G = (0x6B17D1F2E12C4247F8BCE6E563A440F277037D812DEB33A0F4A13945D898C296,
         0x4FE342E2FE1A7F9B8EE7EB4A7C0F9E162BCE33576B315ECECBB6406837BF51F5)
    x, y = mul(priv, G)
    assert f1[4] == b"\x04" + x.to_bytes(32, "big") + y.to_bytes(32, "big"), "Sigma1 eph key != priv*G"
    shared = mul(priv, point(f2[3]))[0].to_bytes(32, "big")
    sha = lambda b: hashlib.sha256(b).digest()
    s2k = hkdf(ipk + f2[1] + f2[3] + sha(s1), shared, b"Sigma2", 16)
    s3k = hkdf(ipk + sha(s1 + s2), shared, b"Sigma3", 16)
    keys = hkdf(ipk + sha(s1 + s2 + s3), shared, b"SessionKeys", 48)
    print("/* Generated by kat.py from `make dump` (deterministic run); stdlib-only recomputation. */")
    print(c_array("KAT_TRANSCRIPT", sha(s1 + s2 + s3)))
    print(c_array("KAT_S2K", s2k))
    print(c_array("KAT_S3K", s3k))
    print(c_array("KAT_KEYS", keys))


if __name__ == "__main__":
    main()
