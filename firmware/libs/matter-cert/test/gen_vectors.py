#!/usr/bin/env python3
"""Extract the certificate vectors from connectedhomeip's CHIPCert_test_vectors.cpp into vectors.h.
Usage: gen_vectors.py <CHIPCert_test_vectors.cpp> > vectors.h
Source: https://github.com/project-chip/connectedhomeip/blob/master/src/credentials/tests/CHIPCert_test_vectors.cpp
Emits, for every name that has both a _Chip (Matter TLV) and a _DER block, the pair, plus a table."""
import re, sys

src = open(sys.argv[1]).read()
blocks = {}
for m in re.finditer(r'sTestCert_(\w+?)_(Chip|DER|PublicKey)\(\(const uint8_t\[\]\)\{(.*?)\}\);', src, re.S):
    name, kind, body = m.groups()
    blocks.setdefault(name, {})[kind] = bytes(int(x, 16) for x in re.findall(r'0x([0-9a-fA-F]{2})', body))

def arr(n, b):
    rows = [', '.join('0x%02x' % x for x in b[i:i + 16]) for i in range(0, len(b), 16)]
    return 'static const uint8_t %s[] = {\n    %s\n};\n' % (n, ',\n    '.join(rows))

print('/* Generated by gen_vectors.py from connectedhomeip CHIPCert_test_vectors.cpp (Apache-2.0). Do not edit. */')
print('#ifndef MT_CERT_VECTORS_H\n#define MT_CERT_VECTORS_H\n#include <stddef.h>\n#include <stdint.h>\n')
names = []
for name, d in blocks.items():
    if 'Chip' in d and 'DER' in d and 'PublicKey' in d:
        names.append(name)
        for k, c in (('Chip', 'tlv'), ('DER', 'der'), ('PublicKey', 'pub')):
            print(arr('v_%s_%s' % (name, c), d[k]))
print('struct vec { const char *name; const uint8_t *tlv; size_t tlv_len, der_len; const uint8_t *der, *pub; };')
print('static const struct vec VECS[] = {')
for n in names:
    print('    { "%s", v_%s_tlv, sizeof v_%s_tlv, sizeof v_%s_der, v_%s_der, v_%s_pub },' % ((n,) * 6))
print('};\n#endif')
