#!/usr/bin/env python3
"""Extract the test device-attestation material (PAI, DAC, DAC key pair, certification declaration) into attest.h.
Usage: gen_attest.py <rs-matter/src/dm/devices/test.rs> > attest.h
Source: rs-matter (Apache-2.0) commit c69916a, which copies connectedhomeip's credentials/examples
(ExamplePAI.cpp FFF1, ExampleDACs.cpp FFF1-8001, the test certification declaration). These are the blobs
Apple Home accepted in the commissioning trace (docs/matter-apple-trace.md)."""
import re, sys

src = open(sys.argv[1]).read()
NAMES = (('PAI_CERT', 'pai'), ('DAC_CERT', 'dac'), ('DAC_PUBKEY', 'dac_pub'), ('DAC_PRIVKEY', 'dac_priv'),
         ('CERT_DECLARATION', 'cd'))
print('/* Generated by gen_attest.py from rs-matter src/dm/devices/test.rs (Apache-2.0). Do not edit.')
print(' * Test DAC/PAI (VID 0xFFF1, PID 0x8001), the DAC key pair and the test certification declaration. */')
print('#ifndef MT_ROOT_ATTEST_H\n#define MT_ROOT_ATTEST_H\n#include <stdint.h>\n')
for rs, c in NAMES:
    m = re.search(r'(?:const|pub const) %s\s*:[^=]*=\s*[^\[]*\[(.*?)\]' % rs, src, re.S)
    b = bytes(int(x, 16) for x in re.findall(r'0x([0-9a-fA-F]{2})', m.group(1)))
    line = src.count('\n', 0, m.start()) + 1
    rows = [', '.join('0x%02x' % x for x in b[i:i + 16]) for i in range(0, len(b), 16)]
    print('/* test.rs line %d: %s (%d bytes) */' % (line, rs, len(b)))
    print('static const uint8_t a_%s[%d] = {\n    %s\n};' % (c, len(b), ',\n    '.join(rows)))
print('\n#endif')
