#!/usr/bin/env python3
"""Writes vectors.h: an upload header made by tools/ota_push.py for a deterministic test image, signed with a
throwaway key (fixed seed, not the OTA signing key), so the device-side receive is tested against the tool.
  ../../../../.venv/bin/python gen_vectors.py > vectors.h      (needs the `cryptography` package)"""
import os, struct, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools"))
import ota_push
from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey

LENGTH, SERIAL = 0x2800, 42


def image():  # same formula as TestImage() in test_ota_receive.c
    img = bytearray((i * 31 + 7) & 0xFF for i in range(LENGTH))
    struct.pack_into("<I", img, ota_push.SERIAL_OFFSET, SERIAL)
    return bytes(img)


def arr(name, data):
    rows = ["    " + ", ".join("0x%02x" % b for b in data[i:i + 12]) for i in range(0, len(data), 12)]
    return "static const uint8_t %s[%d] = {\n%s,\n};\n" % (name, len(data), ",\n".join(rows))


key = Ed25519PrivateKey.from_private_bytes(bytes(range(32)))
pk = key.public_key().public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)
img = image()
print("/* Generated by gen_vectors.py; do not edit. */\n#pragma once\n#include <stdint.h>\n")
print("#define VEC_LENGTH 0x%x\n#define VEC_SERIAL %d\n" % (LENGTH, SERIAL))
print(arr("VEC_PK", pk))
print(arr("VEC_HEADER", ota_push.header(img, key.sign(ota_push.message(img)))))
print(arr("VEC_HEADER_V1", ota_push.header(img, key.sign(ota_push.message(img, True)), True)))
