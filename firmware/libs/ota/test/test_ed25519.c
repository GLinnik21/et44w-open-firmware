static void test_rfc8032(void)
{
    for (size_t i = 0; i < sizeof rfc / sizeof rfc[0]; i++)
        CHECK(crypto_ed25519_check(rfc[i].sig, rfc[i].pk, rfc[i].msg, rfc[i].len) == 0);
}

static void test_tampered(void)
{
    uint8_t sig[64], pk[32], msg[2];
    for (size_t i = 0; i < sizeof rfc / sizeof rfc[0]; i++) {
        memcpy(sig, rfc[i].sig, 64);
        sig[i * 17 % 64] ^= 0x01;
        CHECK(crypto_ed25519_check(sig, rfc[i].pk, rfc[i].msg, rfc[i].len) != 0);
        memcpy(pk, rfc[i].pk, 32);
        pk[i * 7 % 32] ^= 0x20;
        CHECK(crypto_ed25519_check(rfc[i].sig, pk, rfc[i].msg, rfc[i].len) != 0);
        if (rfc[i].len) {
            memcpy(msg, rfc[i].msg, 2);
            msg[0] ^= 0x80;
            CHECK(crypto_ed25519_check(rfc[i].sig, rfc[i].pk, msg, rfc[i].len) != 0);
        }
        CHECK(crypto_ed25519_check(rfc[i].sig, rfc[(i + 1) % 3].pk, rfc[i].msg, rfc[i].len) != 0);
    }
}

/* S' = S + L verifies the same equation; a strict RFC 8032 verifier rejects S >= L. */
static void test_malleated_s_refused(void)
{
    static const uint8_t l[32] = {0xed, 0xd3, 0xf5, 0x5c, 0x1a, 0x63, 0x12, 0x58, 0xd6, 0x9c, 0xf7, 0xa2, 0xde, 0xf9, 0xde, 0x14,
                                  0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x10};
    for (size_t i = 0; i < sizeof rfc / sizeof rfc[0]; i++) {
        uint8_t sig[64];
        memcpy(sig, rfc[i].sig, 64);
        unsigned carry = 0;
        for (int b = 0; b < 32; b++) {
            unsigned v = sig[32 + b] + l[b] + carry;
            sig[32 + b] = (uint8_t) v;
            carry = v >> 8;
        }
        CHECK(carry == 0); /* S + L still fits in 32 bytes for these S */
        CHECK(crypto_ed25519_check(sig, rfc[i].pk, rfc[i].msg, rfc[i].len) != 0);
    }
}

static void test_verifier_kat(void)
{
    CHECK(ota_verifier_ok());
}

void run_ed25519_tests(void)
{
    RUN(test_verifier_kat);
    RUN(test_rfc8032);
    RUN(test_tampered);
    RUN(test_malleated_s_refused);
}
