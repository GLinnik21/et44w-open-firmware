#!/usr/bin/env python3
"""Generate firmware/tools/matter-host/test_credentials.{c,h}: PUBLIC connectedhomeip TEST attestation
material for VID 0xFFF1 / PID 0x8000 (DAC, PAI, Certification Declaration, DAC private key). Stdlib only.

Inputs are fetched from connectedhomeip v1.3-branch (raw.githubusercontent.com) into a cache dir
(default firmware/out-host/test-creds, git-ignored) and pinned by SHA-256, so the output is reproducible.
  python3 tools/matter_gen_test_credentials.py [--cache DIR] [--offline]

Two CDs are emitted (see matter_test_cd.py for the wire format):
  csa_dev   the connectedhomeip example CD kCdForAllExamples (VID 0xFFF1, PIDs 0x8000..0x8063, device type
            0x16), signed by the CSA development CD signer 001 (SKI FE:34:3F:...). rs-matter ships the same
            bytes and an iPhone accepted it (docs/matter-apple-trace.md). This is the default.
  chip_test generated here: VID 0xFFF1, PID 0x8000, device type 0x0301 (thermostat), certification type 0,
            signed with the public Chip-Test-CD-Signing-Key (SKI 62:FA:82:...). Not known to be trusted by
            any controller; for experiments (mh_test_creds_chip_test).
TEST ONLY: all private keys involved are public. Never use this for a real product.
"""
import argparse
import hashlib
import os
import re
import subprocess
import sys
import urllib.request

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import matter_test_cd as cd  # noqa: E402

RAW = "https://raw.githubusercontent.com/project-chip/connectedhomeip/v1.3-branch/"
FILES = {  # name -> (path in repo, sha256)
    "dac.der": ("credentials/test/attestation/Chip-Test-DAC-FFF1-8000-0000-Cert.der",
                "f766d18a73b2ee86aef2609e1093eed1a5d46e17f63d0bbcd8a61a6de36e7e83"),
    "dac_key.der": ("credentials/test/attestation/Chip-Test-DAC-FFF1-8000-0000-Key.der",
                    "cccec4ffa986623f40ecd4323d4e10f3b927e3028916816fdba2f60ce8ed0463"),
    "pai.der": ("credentials/test/attestation/Chip-Test-PAI-FFF1-8000-Cert.der",
                "4f910bbf0e8a0208ea29dba71c549e9da375e792c6b8f271119dfacc1b5ab780"),
    "paa.der": ("credentials/test/attestation/Chip-Test-PAA-FFF1-Cert.der",
                "369eef40616645e5bd3e1bc9db70815d6cf93e9a611973ac20c9cd14c8d60c37"),
    "cd_key.pem": ("credentials/test/certification-declaration/Chip-Test-CD-Signing-Key.pem",
                   "0c07866df161b37f0a9ba193f1026526daea97befa6a79c452e83c77bb4006df"),
    "cd_cert.pem": ("credentials/test/certification-declaration/Chip-Test-CD-Signing-Cert.pem",
                    "f3370d3cd1896c565befa306ba6fbe002007b490692f08bcea9c7490e2ba0a68"),
    "example_creds.cpp": ("src/credentials/examples/DeviceAttestationCredsExample.cpp",
                          "0c590164bf2ba9dbb4df491b3794ed15e49a9ea20d40dcd9c04c232a62775bb1"),
    "csa001.pem": ("credentials/development/cd-certs/CSA_Matter_CD_Signing_Key_001.cert.pem", None),
}
VID, PID = 0xFFF1, 0x8000


def fetch(cache, offline):
    os.makedirs(cache, exist_ok=True)
    for name, (path, want) in FILES.items():
        dst = os.path.join(cache, name)
        if not os.path.exists(dst):
            if offline:
                sys.exit("missing %s (offline)" % dst)
            with urllib.request.urlopen(RAW + path, timeout=30) as r:
                data = r.read()
            with open(dst + ".part", "wb") as f:  # renamed when complete: an interrupted run leaves no cache entry
                f.write(data)
            os.replace(dst + ".part", dst)
        got = hashlib.sha256(open(dst, "rb").read()).hexdigest()
        if want and got != want:
            sys.exit("%s: sha256 %s != pinned %s" % (name, got, want))
        if not want:
            print("note: %s sha256 %s (unpinned, only used for a signature self-check)" % (name, got))


def example_cd(cpp):
    """The VID 0xFFF1 fallback kCdForAllExamples array (third one in the file)."""
    txt = open(cpp).read()
    tail = txt[txt.index("Fall back to the VID=0xFFF1 CD"):]
    m = re.search(r"kCdForAllExamples\[\]\s*=\s*\{(.*?)\};", tail, re.S)
    return bytes(int(x, 16) for x in re.findall(r"0x([0-9a-fA-F]{2})", m.group(1)))


def carr(name, data, doc):
    lines = ["/* %s (%d bytes) */" % (doc, len(data)), "static const uint8_t %s[%d] = {" % (name, len(data))]
    for i in range(0, len(data), 12):
        lines.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 12]) + ",")
    lines.append("};")
    return "\n".join(lines)


HEADER_H = """\
/* GENERATED by tools/matter_gen_test_credentials.py. Do not edit.
 *
 * TEST ONLY. Public connectedhomeip test attestation material for VID 0xFFF1 / PID 0x8000:
 *   DAC  credentials/test/attestation/Chip-Test-DAC-FFF1-8000-0000-{Cert,Key}.der   (key is public!)
 *   PAI  credentials/test/attestation/Chip-Test-PAI-FFF1-8000-Cert.der   (PAA: Chip-Test-PAA-FFF1-Cert.der,
 *        SKI 6A:FD:22:77:1F:51:1F:EC:BF:16:41:97:67:10:DC:DC:31:A1:71:7E)
 *   CD   see the generator: CSA development-signed example CD (default) or one signed with the public
 *        Chip-Test-CD-Signing-Key (mh_test_creds_chip_test).
 * Source tree: project-chip/connectedhomeip, tag/branch v1.3-branch. Controllers show such a device as
 * uncertified; never ship this in a product. */
#ifndef MH_TEST_CREDENTIALS_H
#define MH_TEST_CREDENTIALS_H

#include <stdint.h>
#include "mt_core.h"

#define MH_TEST_VID 0xFFF1u
#define MH_TEST_PID 0x8000u

typedef struct {
    mt_span dac;              /* DER X.509 */
    mt_span pai;              /* DER X.509 */
    mt_span cd;               /* DER CMS SignedData (Certification Declaration) */
    uint8_t dac_priv[32];     /* P-256 private scalar, big endian */
    uint8_t dac_pub[65];      /* uncompressed point 04||X||Y */
    uint16_t vid;
    uint16_t pid;
} mh_test_credentials;

extern const mh_test_credentials mh_test_creds;             /* CD: CSA development-signed example (Apple Home accepts it) */
extern const mh_test_credentials mh_test_creds_chip_test;   /* CD: signed with the public Chip-Test-CD-Signing-Key */

#endif
"""


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    fw = os.path.dirname(here)
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--cache", default=os.path.join(fw, "out-host", "test-creds"))
    ap.add_argument("--out-dir", default=os.path.join(here, "matter-host"))
    ap.add_argument("--offline", action="store_true")
    a = ap.parse_args()
    fetch(a.cache, a.offline)
    p = lambda n: os.path.join(a.cache, n)  # noqa: E731

    dac, pai = open(p("dac.der"), "rb").read(), open(p("pai.der"), "rb").read()
    d = cd.ec_private_scalar(p("dac_key.der"))
    pub = cd._mul(d, cd.G)
    dac_pub = b"\x04" + pub[0].to_bytes(32, "big") + pub[1].to_bytes(32, "big")
    assert dac_pub in dac, "DAC private key does not match the DAC public key"
    assert bytes.fromhex("0603550403") in dac and b"FFF1" in dac and b"8000" in dac, "DAC subject VID/PID"

    cd_csa = example_cd(p("example_creds.cpp"))
    content, ski, r, s = cd.cms_parse(cd_csa)
    csa_ski, csa_pub = cd.cert_ski_and_pub(p("csa001.pem"))
    assert ski == csa_ski and cd.ecdsa_verify(csa_pub, content, r, s), "example CD signature"
    f = cd.cd_decode(content)
    assert f[1] == VID and PID in f[2], "example CD does not cover VID/PID"

    sski, _ = cd.cert_ski_and_pub(p("cd_cert.pem"))
    cd_chip = cd.cms_sign(cd.cd_tlv(VID, [PID], 0x0301, "CSA00000SWC00000-00", 0), sski,
                          cd.ec_private_scalar(p("cd_key.pem")))
    c2, ski2, r2, s2 = cd.cms_parse(cd_chip)
    assert cd.ecdsa_verify(cd.cert_ski_and_pub(p("cd_cert.pem"))[1], c2, r2, s2)

    # Chain check with the system openssl if it can do it (PAA -> PAI -> DAC), informational.
    try:
        pem = lambda n: subprocess.run(["openssl", "x509", "-inform", "der", "-in", p(n)],  # noqa: E731
                                       capture_output=True, check=True).stdout
        open(p("paa.pem"), "wb").write(pem("paa.der"))
        open(p("pai.pem"), "wb").write(pem("pai.der"))
        open(p("dac.pem"), "wb").write(pem("dac.der"))
        rr = subprocess.run(["openssl", "verify", "-CAfile", p("paa.pem"), "-untrusted", p("pai.pem"),
                             p("dac.pem")], capture_output=True, text=True)
        print("openssl verify:", (rr.stdout + rr.stderr).strip().splitlines()[-1])
    except Exception as e:  # noqa: BLE001
        print("openssl chain check skipped:", e)

    c = ["/* GENERATED by tools/matter_gen_test_credentials.py. Do not edit. TEST ONLY: see test_credentials.h. */",
         '#include "test_credentials.h"', "",
         carr("k_dac", dac, "DAC, Chip-Test-DAC-FFF1-8000-0000-Cert.der"), "",
         carr("k_pai", pai, "PAI, Chip-Test-PAI-FFF1-8000-Cert.der"), "",
         carr("k_cd_csa_dev", cd_csa,
              "CD: connectedhomeip kCdForAllExamples (VID FFF1, PIDs 8000..8063), signer CSA dev 001 SKI "
              + ski.hex()), "",
         carr("k_cd_chip_test", cd_chip,
              "CD: VID FFF1 PID 8000 device type 0x0301, signed with Chip-Test-CD-Signing-Key, SKI " + sski.hex()),
         ""]
    for sym, cdname in (("mh_test_creds", "k_cd_csa_dev"), ("mh_test_creds_chip_test", "k_cd_chip_test")):
        c += ["const mh_test_credentials %s = {" % sym,
              "    .dac = { k_dac, sizeof k_dac },", "    .pai = { k_pai, sizeof k_pai },",
              "    .cd = { %s, sizeof %s }," % (cdname, cdname),
              "    .dac_priv = { " + ", ".join("0x%02x" % b for b in d.to_bytes(32, "big")) + " },",
              "    .dac_pub = { " + ", ".join("0x%02x" % b for b in dac_pub) + " },",
              "    .vid = MH_TEST_VID,", "    .pid = MH_TEST_PID,", "};", ""]
    open(os.path.join(a.out_dir, "test_credentials.h"), "w").write(HEADER_H)
    open(os.path.join(a.out_dir, "test_credentials.c"), "w").write("\n".join(c))
    print("wrote test_credentials.{h,c}: DAC %d, PAI %d, CD(csa_dev) %d, CD(chip_test) %d bytes"
          % (len(dac), len(pai), len(cd_csa), len(cd_chip)))


if __name__ == "__main__":
    main()
