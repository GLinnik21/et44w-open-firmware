#!/usr/bin/env python3
"""Generate the Ed25519 key that signs firmware OTA images.

  tools/ota_keygen.py [<private-key-out> [<public-header-out>]] [--force | --header-only]

Defaults: secrets/ota_signing.key (raw 32-byte seed as hex on one line, mode 0600) and
apps/thermostat-matter/ota_pubkey.h (OTA_PUBLIC_KEY_INIT, 32 bytes, for `static const uint8_t key[32]`).
To rewrite the app's header from the existing key, from the repo root:
  python3 firmware/tools/ota_keygen.py --header-only secrets/ota_signing.key firmware/apps/thermostat-matter/ota_pubkey.h
Refuses to overwrite an existing private key without --force. --header-only rewrites just the header
from an existing key. Needs the `cryptography` package.
"""
import argparse, os, sys
try:
    from cryptography.hazmat.primitives import serialization
    from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
except ImportError:
    sys.exit("needs the cryptography package: python3 -m pip install cryptography")

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DEF_KEY = os.path.join(ROOT, "secrets", "ota_signing.key")
DEF_HDR = os.path.join(ROOT, "firmware", "apps", "thermostat-matter", "ota_pubkey.h")


def public_bytes(key):
    return key.public_key().public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)


def write_header(path, pub):
    lines = ["    " + ", ".join("0x%02x" % b for b in pub[i:i + 8]) for i in range(0, len(pub), 8)]
    with open(path, "w") as f:
        f.write("// Generated by tools/ota_keygen.py; public key, not secret.\n"
                "#ifndef OTA_PUBKEY_H\n#define OTA_PUBKEY_H\n\n"
                "#define OTA_PUBLIC_KEY_INIT { \\\n%s \\\n}\n\n#endif\n" % ", \\\n".join(lines))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("private", nargs="?", default=DEF_KEY, help="private key file (hex seed)")
    ap.add_argument("header", nargs="?", default=DEF_HDR, help="C header to write")
    ap.add_argument("--force", action="store_true", help="overwrite an existing private key")
    ap.add_argument("--header-only", action="store_true", help="only rewrite the header from the existing key")
    args = ap.parse_args()

    if args.header_only:
        key = Ed25519PrivateKey.from_private_bytes(bytes.fromhex(open(args.private).read().strip()))
    else:
        if os.path.exists(args.private) and not args.force:
            sys.exit("%s exists. Refusing to overwrite: losing the private key bricks OTA for every deployed "
                     "device (they only accept images signed by it). Use --force if you really mean it." % args.private)
        key = Ed25519PrivateKey.generate()
        seed = key.private_bytes(serialization.Encoding.Raw, serialization.PrivateFormat.Raw,
                                 serialization.NoEncryption())
        os.makedirs(os.path.dirname(os.path.abspath(args.private)), exist_ok=True)
        fd = os.open(args.private, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
        with os.fdopen(fd, "w") as f:
            f.write(seed.hex() + "\n")
        os.chmod(args.private, 0o600)
    write_header(args.header, public_bytes(key))
    print("public key: %s\nheader:     %s" % (public_bytes(key).hex(), args.header))


if __name__ == "__main__":
    main()
