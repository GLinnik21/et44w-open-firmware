"""Generate platform/ambz2/sdk.mk (the Realtek SDK core as build/rules.mk libs) from the SDK's
example project makefile, dropping what this firmware doesn't use.

Usage (from firmware/): python3 tools/gen_sdk_mk.py
"""
import os, re

SDK = "vendor/ameba-rtos-z2"
EXAMPLE_MK = f"{SDK}/project/realtek_amebaz2_v0_example/GCC-RELEASE/application.is.mk"
OUT = "platform/ambz2/sdk.mk"

# Feature areas we don't build. Matched as substrings of source and include paths ("/example/" keeps
# the bare example include dir: SDK core includes wlan_fast_connect/example_wlan_fast_connect.h).
DROP = ["/example/", "/bluetooth/", "/airsync/", "/mqtt/", "coap", "/file_system/fatfs", "/file_system/ftl",
        "/websocket/", "/http2/", "mbedtls-2.4.0", "/common/utilities", "/common/test", "atcmd_bt", "atcmd_mp",
        "atcmd_lwip", "/httpc/", "/httpd/", "amazon", "../src/", "../inc",
        "tls_polarssl.c", "wifi_eap_config.c",  # WPA-Enterprise (EAP-TLS)
        "ota_8710c.c",                          # Realtek's HTTP(S) OTA; we have our own
        "/ssl/ssl_func_stubs/",                # ROM TLS stubs; we use mbedtls for crypto only
        "/api/at_cmd/", "rtl_console.c"]       # AT console: pulls in sscanf + wide-char tables (~50 KiB)

src = open(EXAMPLE_MK).read()
items = lambda var: [m.group(1) for m in re.finditer(r"^\s*%s\s*\+=\s*(\S+)" % var, src, re.M)]
keep = lambda p: not any(d in p for d in DROP)
rel = lambda p: re.sub(r"^(-I)?\.\./\.\./\.\./", "", p)

# The example makefile also lists dirs this SDK release doesn't ship (e.g. .../lib/include): skip those.
inc = [rel(i) for i in items("INCLUDES") if keep(i) and os.path.isdir(f"{SDK}/{rel(i)}")]
srcs = [rel(s) for s in items("SRC_C") if keep(s)]
sram = [rel(s) for s in items("SRAM_C") if keep(s)]
lst = lambda l: " \\\n".join(f"  $(SDK)/{p}" for p in l)

with open(OUT, "w") as f:
    f.write(f"""# GENERATED by tools/gen_sdk_mk.py from the SDK example makefile; edit the generator, not this file.
# Realtek ameba-rtos-z2 core as two libs for build/rules.mk: no examples, BT, MQTT, CoAP, FatFS,
# websockets, HTTP client/server, mbedtls-2.4.0, EAP-TLS or Realtek OTA.

LIBS += sdk sdk_sram
# mbedtls: only ssl_func_stubs.c includes it, for the version macro.
sdk_DEPS := mbedtls
sdk_INC := $(d)/config \\
{lst(inc)}
sdk_SRC := \\
{lst(srcs)}
# The SDK's C predates GCC 14, which turned these warnings into errors.
sdk_CFLAGS := -w -Wno-error=implicit-function-declaration -Wno-error=incompatible-pointer-types \\
  -Wno-error=int-conversion -Wno-error=return-mismatch -Wno-error=implicit-int \\
  -Wno-error=declaration-missing-parameter-type

# Runs from SRAM (power-save entry), so its sections get a .sram prefix.
sdk_sram_SRC := \\
{lst(sram)}
sdk_sram_DEPS := sdk mbedtls
sdk_sram_CFLAGS := $(sdk_CFLAGS)
sdk_sram_POST = $(OBJCOPY) --prefix-alloc-sections .sram $@
""")
print(f"{OUT}: {len(inc)} include dirs, {len(srcs)} sources, {len(sram)} sram sources")
